/*
 * Embeds the sample SVG floor plans in /floorplans into js/data/floorplans.js
 * so the app works when index.html is opened directly from disk (file://),
 * where browsers block fetch() of local files.
 *
 * Usage:  node tools/build-floorplans.js
 * Only needed if you edit the bundled sample SVGs. Real factory drawings are
 * normally imported through the app (Factory Zones → Floors → Import plan).
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const plans = {
  F1: 'floorplans/F1-production.svg',
  F2: 'floorplans/F2-admin-qc.svg',
};

let out = '/* AUTO-GENERATED by tools/build-floorplans.js — sample floor plans (ILLUSTRATIVE DEMO ONLY). */\n';
out += 'window.FAM = window.FAM || {};\nwindow.FAM.FLOORPLANS = {\n';
for (const [key, rel] of Object.entries(plans)) {
  const svg = fs.readFileSync(path.join(root, rel), 'utf8').trim();
  out += `  ${key}: ${JSON.stringify(svg)},\n`;
}
out += '};\n';
fs.writeFileSync(path.join(root, 'js/data/floorplans.js'), out);
console.log('Wrote js/data/floorplans.js');
